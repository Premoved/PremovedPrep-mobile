// The desktop shell modules the Android app runs as they are, bundled from PremovedPrep-App/shell/local
// into .build/src/mobile/core/ by tools/prepare.mjs. Their Node imports are served by src/mobile/shims
// and src/mobile/db/node-sqlite.js; a module needing anything else does not bundle, which is the point:
// a new Node dependency on the desktop must be looked at before it reaches the phone.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const SHELL_MODULES = [
	// Collections: reading and writing PGN (store.js).
	{ name: 'pgn.js', exports: 'default' },
	// Local databases: every query of Search databases and Position databases (db.worker.ts).
	{ name: 'queries.js', exports: 'default' },
	// Local databases: the checks on an imported database (isPrepared), and the indexing itself (db/index.worker.ts).
	{ name: 'index-worker.js', exports: 'default' },
	// The offline FIDE player list: its queries (db/databases.worker.ts) and its builder (db/index.worker.ts).
	{ name: 'player-queries.js', exports: 'default' },
	{ name: 'player-list-worker.js', exports: 'default' },
];

// Constants of database.js the Android app must share: an import is checked against the same versions.
const CONSTANTS = [
	'INDEX_VERSION',
	'POSITIONS_VERSION',
	'LAYOUT',
	'EXPORT_FORMAT',
	'DEFAULT_MAX_PLY',
	// Room a PGN's search database and positions take, per byte of PGN (checked before a run).
	'SEARCH_PER_PGN_BYTE',
	'POSITIONS_PER_PGN_BYTE',
];

export function shimsIn(mobileSrc) {
	return {
		'node:crypto': join(mobileSrc, 'shims', 'crypto.js'),
		'node:zlib': join(mobileSrc, 'shims', 'zlib.js'),
		'node:fs': join(mobileSrc, 'shims', 'fs.js'),
		'node:sqlite': join(mobileSrc, 'db', 'node-sqlite.js'),
		'node:os': join(mobileSrc, 'shims', 'os.js'),
		'node:path': join(mobileSrc, 'shims', 'path.js'),
		'node:worker_threads': join(mobileSrc, 'shims', 'worker_threads.js'),
		'node:readline': join(mobileSrc, 'shims', 'readline.js'),
		'node:stream': join(mobileSrc, 'shims', 'stream.js'),
	};
}

/**
 * esbuild: the build's esbuild module. desktop: the desktop app's folder. mobileSrc: .build/src/mobile.
 * alias / inject: replace the defaults (the tests use node:sqlite itself and Node's own Buffer).
 */
export async function bundleShellModules({ esbuild, desktop, mobileSrc, out, alias, inject, define, nodePaths = [] }) {
	mkdirSync(out, { recursive: true });
	for (const { name } of SHELL_MODULES) {
		const source = join(desktop, 'shell', 'local', name);
		// The desktop modules are CommonJS: their module.exports becomes the default export.
		await esbuild.build({
			stdin: {
				contents: `import desktop from ${JSON.stringify(source)};\nexport default desktop;\n`,
				resolveDir: join(desktop, 'shell', 'local'),
				sourcefile: `entry-${name}`,
			},
			outfile: join(out, name),
			bundle: true,
			format: 'esm',
			platform: 'browser',
			target: 'es2022',
			alias: alias ?? shimsIn(mobileSrc),
			inject: inject ?? [join(mobileSrc, 'shims', 'buffer-global.js'), join(mobileSrc, 'shims', 'process-global.js')],
			// Where the indexer starts its replay workers from (shims/worker_threads.js takes the file name).
			define: define ?? { __dirname: '"/shell/local"', __filename: '"/shell/local/index-worker.js"' },
			nodePaths,
			logLevel: 'warning',
			banner: { js: `// Generated by tools/prepare.mjs from PremovedPrep-App/shell/local/${name}. Do not edit.` },
		});
		writeFileSync(
			join(out, name.replace(/\.js$/, '.d.ts')),
			'// Generated by tools/prepare.mjs. Do not edit.\ndeclare const desktop: any;\nexport default desktop;\n',
		);
	}
}

/**
 * The indexer's replay workers: the desktop's replay-worker.js, bundled as a script of its own that the
 * indexing worker starts as Web Workers (shims/worker_threads.js), served at /replay-worker.js.
 */
export async function bundleReplayWorker({ esbuild, desktop, mobileSrc, outFile, nodePaths = [] }) {
	await esbuild.build({
		entryPoints: [join(desktop, 'shell', 'local', 'replay-worker.js')],
		outfile: outFile,
		bundle: true,
		format: 'iife',
		platform: 'browser',
		target: 'es2022',
		alias: { ...shimsIn(mobileSrc), 'node:worker_threads': join(mobileSrc, 'shims', 'worker_threads-child.js') },
		inject: [join(mobileSrc, 'shims', 'buffer-global.js'), join(mobileSrc, 'shims', 'process-global.js')],
		nodePaths,
		logLevel: 'warning',
		banner: { js: '// Generated by tools/prepare.mjs from PremovedPrep-App/shell/local/replay-worker.js. Do not edit.' },
	});
}

// Read from the desktop's database.js, so a change of version there reaches the Android app's checks.
export function writeConstants({ desktop, out }) {
	const text = readFileSync(join(desktop, 'shell', 'local', 'database.js'), 'utf8');
	const lines = ['// Generated by tools/prepare.mjs from PremovedPrep-App/shell/local/database.js. Do not edit.'];
	for (const name of CONSTANTS) {
		const found = new RegExp(`^const ${name} = (\\d+(?:\\.\\d+)?);`, 'm').exec(text);
		if (!found) {
			throw new Error(`database.js no longer has const ${name} = <number>;`);
		}
		lines.push(`export const ${name} = ${found[1]};`);
	}
	mkdirSync(out, { recursive: true });
	writeFileSync(join(out, 'database-constants.js'), `${lines.join('\n')}\n`);
	writeFileSync(
		join(out, 'database-constants.d.ts'),
		`${CONSTANTS.map((name) => `export declare const ${name}: number;`).join('\n')}\n`,
	);
}
