function replaceOnce(text, find, replace, what, fail) {
	const count = text.split(find).length - 1;
	if (count !== 1) {
		fail(`THIRD-PARTY.md: "${what}" was found ${count} times in the desktop app's file (expected once).`);
	}
	return text.replace(find, () => replace);
}

function replaceBetween(text, start, end, replace, what, fail, keepEnd = false) {
	const from = text.indexOf(start);
	const to = from < 0 ? -1 : text.indexOf(end, from);
	if (from < 0 || to < 0 || text.indexOf(start, from + 1) >= 0) {
		fail(`THIRD-PARTY.md: "${what}" was not found once in the desktop app's file.`);
	}
	return text.slice(0, from) + replace + text.slice(keepEnd ? to : to + end.length);
}

export function writeThirdParty({ desktop, root, out, fail }) {
	const source = join(desktop, 'THIRD-PARTY.md');
	if (!existsSync(source)) {
		fail(`the desktop app has no THIRD-PARTY.md at ${source}.`);
	}
	let text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
	text = replaceOnce(text, LIBRARIES_FIND, LIBRARIES_REPLACE, 'Electron, Chromium, Node.js and Stockfish rows', fail);
	text = replaceOnce(text, CONVEYED_FIND, CONVEYED_REPLACE, 'Stockfish is conveyed as a binary', fail);
	text = replaceBetween(text, PATHS_START, PATHS_END, PATHS_REPLACE, 'paths in the installed application', fail);
	text = replaceBetween(text, ENGINE_START, ENGINE_END, ENGINE_REPLACE, 'Engine section', fail, true);

	const target = join(out, 'public', 'licenses');
	mkdirSync(target, { recursive: true });
	writeFileSync(join(target, 'THIRD-PARTY.md'), text);
	cpSync(join(root, 'LICENSE'), join(target, 'LICENSE'));

	const gpl = join(root, 'node_modules', '@lichess-org', 'chessground', 'LICENSE');
	if (!existsSync(gpl)) {
		fail('the GPL-3.0 text was not found (node_modules/@lichess-org/chessground/LICENSE): run `npm install` first.');
	}
	cpSync(gpl, join(target, 'GPL-3.0.txt'));
}
