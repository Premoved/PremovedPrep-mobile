// /licenses/THIRD-PARTY.md). Built from the desktop app's THIRD-PARTY.md, with the parts that differ on
// Android replaced: Capacitor instead of Electron, the APK's paths, and two engines (Stockfish, Lc0).
// Like tools/patches.mjs, each replaced part must be found exactly once, or the build stops.
//
// prepare.mjs writes THIRD-PARTY.md, LICENSE and GPL-3.0.txt into .build/public/licenses/ (the build copies
// them into www/licenses/); tools/licenses.mjs adds 3rdpartylicenses.txt after `ng build`.

